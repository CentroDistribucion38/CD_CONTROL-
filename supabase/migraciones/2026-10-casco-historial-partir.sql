insert into public.casco_registros as r
  (fecha, ubicacion, sku, inventario, hl, hl_estiba, origen, nota)
select p.fecha, p.ubicacion, p.sku,
       case when x.f is not null then round(p.hl / x.f, 2) end,
       p.hl, x.f, 'importado', 'Hoja PARTIR: total inventario + baja, en HL'
  from _partir p
  cross join lateral (select public.casco_hl_estiba(p.sku) as f) x
on conflict (fecha, ubicacion, sku) do update set
  inventario = excluded.inventario, hl = excluded.hl, hl_estiba = excluded.hl_estiba,
  actualizado_en = now()
where r.origen = 'importado';

-- REVISIÓN: HL de la hoja que no da estibas enteras con el maestro de hoy,
-- o materiales sin factor en el maestro.
select p.sku,
       count(*) as renglones,
       count(*) filter (where x.f is null) as sin_factor_en_maestro,
       count(*) filter (where x.f is not null and abs(p.hl / x.f - round(p.hl / x.f)) > 0.02) as no_enteras,
       max(x.f) as hl_por_estiba_maestro
  from _partir p
  cross join lateral (select public.casco_hl_estiba(p.sku) as f) x
 group by p.sku
having count(*) filter (where x.f is null) > 0
    or count(*) filter (where x.f is not null and abs(p.hl / x.f - round(p.hl / x.f)) > 0.02) > 0
 order by p.sku;

